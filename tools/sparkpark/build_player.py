"""SparkPark: build the game with llvm-mingw, the way the player's PC will (no MSVC).

Two halves, so that what SparkPark ships contains no game code:

  runtime  (developer side, shipped): compile recomp/runtime, patches, boot and gpu into
           libsparkpark_runtime.a. The only game-specific input is recomp_funcs.h, which here is
           generated from the public function list (config/R8AE01/symbols.txt) and
           recomp/patches/hooks.txt, not from a disc: prototypes only, no code or data.
  game     (player side, never shipped): compile the C that tools/recomp/recomp.py made from the
           player's main.dol and link it with the runtime library into SparkPark.exe.

  python tools/sparkpark/build_player.py runtime --out <dir>
  python tools/sparkpark/build_player.py game --gen <gen dir> --runtime <dir> --exe <SparkPark.exe>

Progress is printed one line per step ("[12/76] recomp_011.c"), for the builder to read.
The C flags follow upstream's clang build (Android): -O2 -std=gnu11 -w.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import glob
import os
import re
import subprocess
import sys
import time

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
LLVM = os.environ.get("SPARKPARK_LLVM", r"D:\Tools\llvm-mingw-20261020-ucrt-x86_64")
CFLAGS = ["-O2", "-std=gnu11", "-w"]
# SPARKPARK_DEBUG_INFO=1 (developers only, for profiling): CodeView debug info and a PDB beside the
# exe, so the sampling profiler (RECOMP_PROFILE, boot.c) can name functions in this build too. The
# code generated is the same; only the symbols are added. Player builds leave it off.
DEBUG_INFO = os.environ.get("SPARKPARK_DEBUG_INFO") == "1"
if DEBUG_INFO:
    CFLAGS = CFLAGS + ["-gcodeview"]
# Public builds: no debug settings menu (as upstream's --public); keep the call trace for crash reports.
DEFINES = ["RECOMP_TRACE"]
SYSLIBS = ["opengl32", "user32", "gdi32", "ole32", "windowscodecs", "comdlg32", "shell32", "winmm",
           "dbghelp", "d3d11", "dxgi", "dxguid", "comctl32"]
# MSVC gets this from #pragma comment(linker, ...) in import_win32.c; for lld it is a resource.
MANIFEST = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
  <dependency><dependentAssembly>
    <assemblyIdentity type="win32" name="Microsoft.Windows.Common-Controls" version="6.0.0.0"
                      processorArchitecture="*" publicKeyToken="6595b64144ccf1df" language="*"/>
  </dependentAssembly></dependency>
</assembly>
"""


def vulkan_sdk() -> str | None:
    """The Vulkan SDK (VULKAN_SDK), for the runtime's Vulkan device: its headers, and glslc to compile
    SparkPark's own shaders (recomp/gpu/vk_shaders) to SPIR-V. Developer side only: the player's PC
    needs no SDK, since the game loads Vulkan from the graphics driver as it starts."""
    sdk = os.environ.get("VULKAN_SDK")
    if sdk and os.path.exists(os.path.join(sdk, "Include", "vulkan", "vulkan.h")):
        return sdk
    return None


def vulkan_shaders_header(sdk: str, out_dir: str) -> None:
    """vk_shaders.h as tools/recomp/build.py makes it: each shader as a C array of SPIR-V."""
    glslc = os.path.join(sdk, "Bin", "glslc.exe")
    parts = ["/* Generated by tools/sparkpark/build_player.py from recomp/gpu/vk_shaders. */\n"]
    for src in sorted(glob.glob(os.path.join(ROOT, "recomp", "gpu", "vk_shaders", "*.*"))):
        base = os.path.basename(src)
        name = "kSpv_" + base.replace(".", "_")
        opt = [] if base == "gx.frag" else ["-O"]  # as build.py: the driver specializes gx.frag
        builds = ([(f"{name}_{n}", [f"-DTEX_IO={n}"]) for n in range(9)] if base in ("gx.vert", "gx.frag")
                  else [(name, [])])
        for out_name, defs in builds:
            code = subprocess.check_output([glslc, "--target-env=vulkan1.3", *opt, *defs, "-mfmt=c", "-o", "-", src],
                                           text=True)
            parts.append(f"static const uint32_t {out_name}[] = {code.strip()};\n")
        if len(builds) > 1:
            parts.append(f"static const uint32_t* const {name}[] = {{{', '.join(b for b, _ in builds)}}};\n")
            parts.append(f"static const size_t {name}_size[] = {{{', '.join(f'sizeof({b})' for b, _ in builds)}}};\n")
    with open(os.path.join(out_dir, "vk_shaders.h"), "w", newline="\n") as f:
        f.write("".join(parts))


def tool(name: str) -> str:
    return os.path.join(LLVM, "bin", name + ".exe")


def runtime_sources() -> list[str]:
    srcs = []
    for d in ("runtime", "patches", "boot", "gpu"):
        srcs += glob.glob(os.path.join(ROOT, "recomp", d, "*.c"))
    return sorted(s for s in srcs if not s.endswith("_android.c"))


def public_funcs_header(out_dir: str) -> str:
    """recomp_funcs.h from the public function list and hooks.txt alone (no disc)."""
    sym_re = re.compile(r"^(\S+) = (\.text|\.init):0x([0-9A-Fa-f]+); // type:function")
    addrs = set()
    for line in open(os.path.join(ROOT, "config", "R8AE01", "symbols.txt"), encoding="utf-8"):
        m = sym_re.match(line)
        if m:
            addrs.add(int(m[3], 16))
    hooks = set()
    for line in open(os.path.join(ROOT, "recomp", "patches", "hooks.txt"), encoding="utf-8"):
        line = line.split("#")[0].strip()
        if line:
            hooks.add(int(line.split()[0], 16))
    missing = hooks - addrs
    if missing:
        sys.exit("hooks not in symbols.txt: " + ", ".join(f"{a:08X}" for a in sorted(missing)))
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "recomp_funcs.h")
    with open(path, "w", newline="\n") as h:
        h.write("/* SparkPark: generated by tools/sparkpark/build_player.py from config/R8AE01/symbols.txt and\n"
                " * recomp/patches/hooks.txt. Prototypes only: no game code. */\n#pragma once\n#include \"ppc.h\"\n\n")
        for a in sorted(addrs):
            h.write(f"void f_{a:08X}(ppc_t* c);\n")
            if a in hooks:
                h.write(f"void f_{a:08X}_orig(ppc_t* c);\n")
    return path


def compile_all(srcs: list[str], obj_dir: str, includes: list[str], label: str,
                extra_defines: tuple[str, ...] = ()) -> list[str]:
    os.makedirs(obj_dir, exist_ok=True)
    inc = [f"-I{i}" for i in includes]
    defs = [f"-D{d}" for d in (*DEFINES, *extra_defines)]
    objs = [os.path.join(obj_dir, os.path.splitext(os.path.basename(s))[0] + ".o") for s in srcs]

    def one(i):
        r = subprocess.run([tool("clang"), *CFLAGS, *defs, *inc, "-c", srcs[i], "-o", objs[i]],
                           capture_output=True, text=True)
        return i, r

    done = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        for i, r in pool.map(one, range(len(srcs))):
            done += 1
            if r.returncode != 0:
                sys.stderr.write(r.stdout + r.stderr)
                sys.exit(f"error: compiling {os.path.basename(srcs[i])} failed")
            print(f"[{done}/{len(srcs)}] {label} {os.path.basename(srcs[i])}", flush=True)
    return objs


def cmd_runtime(a) -> int:
    t0 = time.time()
    hdr_dir = os.path.join(a.out, "include")
    public_funcs_header(hdr_dir)
    includes = [os.path.join(ROOT, "recomp", "runtime"), hdr_dir, os.path.join(ROOT, "src"),
                os.path.join(ROOT, "recomp", "gpu")]
    sdk = vulkan_sdk()
    extra = ()
    if sdk:
        vulkan_shaders_header(sdk, hdr_dir)
        includes.append(os.path.join(sdk, "Include"))
        extra = ("RECOMP_VULKAN",)
        print(f"runtime: with the Vulkan device ({sdk})", flush=True)
    else:
        print("runtime: no Vulkan SDK (VULKAN_SDK): OpenGL only", flush=True)
    objs = compile_all(runtime_sources(), os.path.join(a.out, "obj"), includes, "runtime", extra)
    lib = os.path.join(a.out, "libsparkpark_runtime.a")
    if os.path.exists(lib):
        os.remove(lib)
    subprocess.check_call([tool("llvm-ar"), "rcs", lib, *objs])
    with open(os.path.join(a.out, "app.manifest"), "w", newline="\n") as f:
        f.write(MANIFEST)
    with open(os.path.join(a.out, "app.rc"), "w", newline="\n") as f:
        f.write('1 24 "app.manifest"\n')
    subprocess.check_call([tool("llvm-windres"), os.path.join(a.out, "app.rc"), "-O", "coff",
                           "-o", os.path.join(a.out, "app_manifest.o")], cwd=a.out)
    print(f"runtime: {lib} ({os.path.getsize(lib) / 1e6:.1f} MB) in {time.time() - t0:.0f} s", flush=True)
    return 0


def cmd_game(a) -> int:
    t0 = time.time()
    srcs = sorted(glob.glob(os.path.join(a.gen, "*.c")))
    if not srcs:
        sys.exit(f"no generated code in {a.gen}: run tools/recomp/recomp.py first")
    includes = [os.path.join(ROOT, "recomp", "runtime"), a.gen]
    objs = compile_all(srcs, os.path.join(a.work, "obj"), includes, "game")
    t1 = time.time()
    print("linking", flush=True)
    symbols = ["-g", f"-Wl,--pdb={os.path.splitext(a.exe)[0]}.pdb"] if DEBUG_INFO else ["-s"]
    subprocess.check_call([tool("clang"), "-o", a.exe, *objs, os.path.join(a.runtime, "libsparkpark_runtime.a"),
                           os.path.join(a.runtime, "app_manifest.o"), *[f"-l{l}" for l in SYSLIBS], *symbols])
    print(f"game: {a.exe} ({os.path.getsize(a.exe) / 1e6:.1f} MB): compile {t1 - t0:.0f} s, "
          f"link {time.time() - t1:.0f} s", flush=True)
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="build_player.py")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("runtime")
    r.add_argument("--out", required=True)
    g = sub.add_parser("game")
    g.add_argument("--gen", required=True, help="tools/recomp/recomp.py output")
    g.add_argument("--runtime", required=True, help="the folder 'runtime' wrote")
    g.add_argument("--work", required=True, help="scratch folder for objects")
    g.add_argument("--exe", required=True)
    a = ap.parse_args(argv)
    return {"runtime": cmd_runtime, "game": cmd_game}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
