"""Audit a SparkPark release zip: prove it contains no game code or data.

Reads the zip itself, and compares it with the developer's own extracted disc (which never leaves
the developer's PC; nothing from it is printed). Writes a file list and a report.

  python builder/audit.py --zip SparkPark-v0.2.0-alpha.zip --disc <extracted disc dir>
                          --dol <main.dol> --origins <dir>=<label> ... --out <report dir>

Checks:
  1. every file, with its size (files.txt);
  2. no file is identical to any file on the disc or to main.dol;
  3. no file contains 48 or more contiguous bytes of main.dol (every 32-byte window of main.dol
     that isn't trivially repetitive, searched at a 16-byte stride through every file's contents);
  4. no file carries the recompiler's output: its header line, PPC_TRACE( or generated
     "f_8XXXXXXX(c);" calls;
  5. no Wii game data formats, by extension or by signature (U8, Yaz0, THP, NW4R files...);
  6. the runtime library defines only the hand-written hooks of hooks.txt (game addresses as names),
     never translated game functions;
  7. each program and DLL is byte-identical to its official download (origins), or is SparkPark's own.
"""
import argparse
import collections
import hashlib
import os
import re
import subprocess
import sys
import tempfile
import zipfile

GAME_EXT = {".iso", ".rvz", ".wbfs", ".wia", ".gcz", ".ciso", ".nfs", ".dol", ".rel", ".elf", ".dan", ".thp",
            ".brstm", ".brsar", ".brwsd", ".brbnk", ".arc", ".szs", ".carc", ".tpl", ".bnr", ".dac", ".rlb", ".efb",
            ".brres", ".brlyt", ".brlan", ".brfnt", ".breff", ".breft", ".bmg", ".sav"}
GEN_NAMES = re.compile(r"(^|/)(recomp_\d{3}\.c|recomp_table\.c|recomp_funcs\.h|coverage\.txt)$")
# Signatures of Wii/NW4R/Nintendo file formats, at offset 0.
SIGS = {b"U\xaa8-": "U8 archive", b"Yaz0": "Yaz0", b"THP\0": "THP movie", b"RSTM": "BRSTM", b"RSAR": "BRSAR",
        b"RWSD": "BRWSD", b"RBNK": "BRBNK", b"RLYT": "BRLYT", b"RLAN": "BRLAN", b"RFNT": "BRFNT", b"bres": "BRRES",
        b"REFF": "BREFF", b"REFT": "BREFT", b"MESGbmg1": "BMG"}
MARKERS = [b"Generated by tools/recomp/recomp.py", b"PPC_TRACE("]
GEN_CALL = re.compile(rb"\bf_8[0-9A-F]{7}\(c\);")


def sha256(b):
    return hashlib.sha256(b).hexdigest()


def dol_windows(dol: bytes, n=32):
    """Every n-byte window of main.dol with at least 10 different byte values, mapped to "code"
    (a text section, and not printable text) or "data" (data sections, or text in a code section,
    such as the Metrowerks debugger's banner string in .init)."""
    import struct
    offs = struct.unpack(">18I", dol[0:72])
    sizes = struct.unpack(">18I", dol[0x90:0x90 + 72])
    out = {}
    for sec, (o, s) in enumerate(zip(offs, sizes)):
        for i in range(o, o + s - n + 1) if s else ():
            w = dol[i:i + n]
            if len(set(w)) >= 10:
                printable = all(32 <= c < 127 or c in (0, 9, 10, 13) for c in w)
                out.setdefault(w, "code" if sec < 7 and not printable else "data")
    return out


RUN_LIMIT = 512  # a contiguous match this long in a SparkPark-made file would be copied game data
NAME_LISTS = ("recompiler/config/R8AE01/symbols.txt", "recompiler/recomp/patches/hooks.txt")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", required=True)
    ap.add_argument("--disc", required=True)
    ap.add_argument("--dol", required=True)
    ap.add_argument("--origins", nargs="*", default=[], help="<folder>=<label>: official downloads to match")
    ap.add_argument("--hooks", required=True)
    ap.add_argument("--llvm-nm", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rep = []
    say = lambda s="": (rep.append(s), print(s))

    z = zipfile.ZipFile(a.zip)
    infos = [i for i in z.infolist() if not i.is_dir()]
    with open(os.path.join(a.out, "files.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        for i in sorted(infos, key=lambda i: i.filename):
            f.write(f"{i.file_size:>12,}  {i.filename}\n")
    tops = collections.defaultdict(lambda: [0, 0])
    for i in infos:
        parts = i.filename.split("/")
        key = parts[1] if len(parts) > 2 else parts[-1]
        tops[key][0] += 1
        tops[key][1] += i.file_size
    say(f"SparkPark release audit: {os.path.basename(a.zip)} ({os.path.getsize(a.zip):,} bytes, sha256 "
        f"{sha256(open(a.zip, 'rb').read())})")
    say(f"1. Files: {len(infos):,}, {sum(i.file_size for i in infos):,} bytes unpacked (full list: files.txt)")
    for k, (n, s) in sorted(tops.items(), key=lambda kv: -kv[1][1]):
        say(f"     {k:<28} {n:>5} files {s:>14,} bytes")

    # Official downloads (byte-identical files can't carry anything of ours or the game's).
    origin = {}
    for spec in a.origins:
        folder, label = spec.split("=", 1)
        for d, _, fs in os.walk(folder):
            for f in fs:
                origin.setdefault(sha256(open(os.path.join(d, f), "rb").read()), label)

    # Disc reference (local only).
    disc_hashes = {}
    for d, _, fs in os.walk(a.disc):
        for f in fs:
            disc_hashes[sha256(open(os.path.join(d, f), "rb").read())] = 1
    dol = open(a.dol, "rb").read()
    disc_hashes[sha256(dol)] = 1
    say(f"   Reference: {len(disc_hashes)} distinct files from the extracted disc + main.dol "
        f"({len(dol):,} bytes; local, not included)")

    same, marker_hits, ext_hits, sig_hits, gen_names = [], collections.Counter(), [], [], []
    code_hits, data_hits, data_run = collections.Counter(), collections.Counter(), {}
    windows = dol_windows(dol)
    say(f"   main.dol windows searched for: {sum(1 for v in windows.values() if v == 'code'):,} code, "
        f"{sum(1 for v in windows.values() if v == 'data'):,} data")
    member_hash = {}
    for i in infos:
        data = z.read(i)
        member_hash[i.filename] = sha256(data)
        if member_hash[i.filename] in disc_hashes:
            same.append(i.filename)
        run = best = 0
        for k in range(0, len(data) - 31, 16):
            kind = windows.get(data[k:k + 32])
            if kind == "code":
                code_hits[i.filename] += 1
            if kind:
                data_hits[i.filename] += kind == "data"
                run += 16
                best = max(best, run + 16)
            else:
                run = 0
        if best:
            data_run[i.filename] = best
        for m in MARKERS:
            if m in data:
                marker_hits[(i.filename, m.decode())] += data.count(m)
        g = len(GEN_CALL.findall(data))
        if g:
            marker_hits[(i.filename, "f_8XXXXXXX(c); calls")] += g
        ext = os.path.splitext(i.filename)[1].lower()
        if ext in GAME_EXT:
            ext_hits.append(i.filename)
        if GEN_NAMES.search(i.filename):
            gen_names.append(i.filename)
        for s, what in SIGS.items():
            if data.startswith(s):
                sig_hits.append(f"{i.filename} ({what})")

    say(f"2. Files identical to a disc file or main.dol: {len(same)}" + "".join(f"\n     {s}" for s in same))
    say(f"3a. Files containing main.dol CODE (48+ contiguous bytes of its code sections): {len(code_hits)}" +
        "".join(f"\n     {f}: {n}" for f, n in code_hits.most_common()))
    short = lambda f: f.split("/", 1)[1]
    # Data-section matches are expected in small amounts (digit and counting tables, the JPEG
    # zig-zag order, C library strings, class names in the public function list); copied game
    # data would show as a long contiguous run.
    official = lambda f: member_hash[f] in origin
    ours = [f for f in data_run if not official(f)]
    long_runs = [f for f in ours if data_run[f] >= RUN_LIMIT and short(f) not in NAME_LISTS]
    say(f"3b. main.dol DATA matches: {len(data_hits)} files. Longest contiguous run, files made for this "
        f"release:" + "".join(f"\n     {short(f):<70} {data_run[f]:>6} bytes" for f in sorted(ours, key=lambda f: -data_run[f])) +
        f"\n   ...and in official downloads (byte-identical to them; top 5):" +
        "".join(f"\n     {short(f):<70} {data_run[f]:>6} bytes"
                for f in sorted([f for f in data_run if official(f)], key=lambda f: -data_run[f])[:5]) +
        f"\n   Runs of {RUN_LIMIT}+ bytes in files made for this release, outside the public name lists "
        f"(symbols.txt, hooks.txt): {len(long_runs)}" + "".join(f"\n     {short(f)}" for f in long_runs))
    # The recompiler itself and the header defining PPC_TRACE contain these as templates.
    tool_src = ("recompiler/tools/recomp/recomp.py", "recompiler/recomp/runtime/ppc.h")
    marker_out = {k: n for k, n in marker_hits.items() if short(k[0]) not in tool_src}
    say(f"4. Recompiler output markers outside the recompiler's own source: {sum(marker_out.values())}" +
        "".join(f"\n     {f}: {n} x {m}" for (f, m), n in marker_out.items()) +
        "\n   (in its source, as templates: " +
        ", ".join(f"{short(f)} {n} x {m}" for (f, m), n in marker_hits.items() if short(f) in tool_src) + ")" +
        f"\n   Generated file names (recomp_NNN.c, recomp_table.c, recomp_funcs.h, coverage.txt): {len(gen_names)}")
    say(f"5. Game-format extensions: {len(ext_hits)}; game-format signatures: {len(sig_hits)}" +
        "".join(f"\n     {s}" for s in ext_hits + sig_hits))

    # 6. The runtime library's symbols.
    lib = next(i for i in infos if i.filename.endswith("libsparkpark_runtime.a"))
    hooks = set()
    for line in open(a.hooks, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if line:
            hooks.add(int(line.split()[0], 16))
    with tempfile.TemporaryDirectory() as td:
        p = os.path.join(td, "lib.a")
        open(p, "wb").write(z.read(lib))
        nm = subprocess.run([a.llvm_nm, "--defined-only", p], capture_output=True, text=True).stdout
        und = subprocess.run([a.llvm_nm, "--undefined-only", p], capture_output=True, text=True).stdout
        ar = os.path.join(os.path.dirname(a.llvm_nm), "llvm-ar.exe")
        members = sorted(subprocess.run([ar, "t", p], capture_output=True, text=True).stdout.split())
    defined_f = {int(m.group(1), 16) for m in re.finditer(r" T f_([0-9A-F]{8})$", nm, re.M)}
    undefined_f = set(re.findall(r" U f_([0-9A-F]{8}(?:_orig)?)$", und, re.M))
    say(f"6. Runtime library: {len(members)} objects: " + ", ".join(m.replace(".o", "") for m in members))
    say(f"   Defines {len(defined_f)} f_XXXXXXXX functions; not in hooks.txt: {len(defined_f - hooks)}"
        f" (every one is a hand-written hook named after the game address it replaces)")
    say(f"   Refers to {len(undefined_f)} game functions by address (resolved only when linked on the player's PC)")

    # 7. Origins of programs and DLLs.
    say("7. Programs and DLLs:")
    for i in sorted(infos, key=lambda i: i.filename):
        if os.path.splitext(i.filename)[1].lower() in (".exe", ".dll", ".pyd"):
            src = origin.get(member_hash[i.filename], "SparkPark (built for this release)"
                             if i.filename.endswith("/SparkPark.exe") else "UNKNOWN")
            say(f"     {i.filename.split('/', 1)[1]:<48} {i.file_size:>12,}  {src}")
    unknown = [i.filename for i in infos if os.path.splitext(i.filename)[1].lower() in (".exe", ".dll", ".pyd")
               and member_hash[i.filename] not in origin and not i.filename.endswith("/SparkPark.exe")]
    ok = not (same or code_hits or long_runs or marker_out or ext_hits or sig_hits or gen_names or
              (defined_f - hooks) or unknown)
    say()
    say("RESULT: " + ("PASS. No translated or compiled game code and no disc data in the zip."
                      if ok else "FAIL. See above."))
    with open(os.path.join(a.out, "report.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(rep) + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
